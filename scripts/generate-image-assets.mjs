#!/usr/bin/env node
/**
 * Builds `src/data/imageAssets.ts` from the files under `public/images` and
 * `src/assets`.
 *
 * Public files are referenced by URL. Bundled files are imported so Vite can
 * hash them, which keeps the admin picker and the runtime previews in sync.
 * Image values stored in Supabase should use `sourcePath` (for example
 * `/images/enemies/Mushroom.png` or `/src/assets/sword.png`) because those
 * paths stay stable across builds.
 */
import { mkdirSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { basename, extname, join, relative, sep } from "node:path";

const root = process.cwd();
const IMAGE_EXTENSIONS = new Set([".png", ".jpg", ".jpeg", ".webp", ".gif", ".svg"]);
const SOURCES = [
  { dir: join(root, "public/images"), public: true },
  { dir: join(root, "src/assets"), public: false },
];

const CHARACTER_NAMES = new Set([
  "portrait",
  "wizard",
  "warrior",
  "rogue",
  "rogue-1",
  "cleric",
  "bard",
  "barbarian",
  "assassin",
]);
const ITEM_NAMES = new Set([
  "sword",
  "bow-v1",
  "staff",
  "spear",
  "dagger",
  "health-potion",
  "mana-potion",
]);

function walk(dir) {
  if (!statSync(dir, { throwIfNoEntry: false })) return [];
  const entries = [];
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const fullPath = join(dir, entry.name);
    if (entry.isDirectory()) entries.push(...walk(fullPath));
    else if (IMAGE_EXTENSIONS.has(extname(entry.name).toLowerCase())) entries.push(fullPath);
  }
  return entries;
}

function categorize(sourcePath, filename) {
  const lowerPath = sourcePath.toLowerCase();
  const stem = basename(filename, extname(filename)).toLowerCase();

  if (lowerPath.includes("/spells/")) return "spells";
  if (lowerPath.includes("/enemies/") || lowerPath.includes("enemy")) return "enemies";
  if (lowerPath.includes("/characters/npc/") || lowerPath.includes("/npc/")) return "npc";
  if (lowerPath.includes("/characters/")) return "characters";
  if (lowerPath.includes("/equipment/") || lowerPath.includes("/items/")) return "items";
  if (lowerPath.includes("/background") || lowerPath.includes("background")) {
    return "backgrounds";
  }
  if (ITEM_NAMES.has(stem)) return "items";
  if (CHARACTER_NAMES.has(stem)) return "characters";
  return "other";
}

function humanize(filename) {
  return basename(filename, extname(filename))
    .replace(/[-_]+/g, " ")
    .replace(/\b\w/g, (letter) => letter.toUpperCase());
}

const assets = [];
let importIndex = 0;

for (const source of SOURCES) {
  const files = walk(source.dir).sort((a, b) => a.localeCompare(b));
  for (const file of files) {
    const sourcePath = source.public
      ? `/${relative(join(root, "public"), file).split(sep).join("/")}`
      : `/${relative(root, file).split(sep).join("/")}`;
    const category = categorize(sourcePath, file);
    let src;
    if (source.public) {
      src = sourcePath;
    } else {
      const identifier = `bundledAsset${importIndex++}`;
      const importPath = `@/${relative(join(root, "src"), file).split(sep).join("/")}`;
      assets.push({ identifier, importPath, sourcePath, category, label: humanize(file) });
      continue;
    }
    assets.push({
      identifier: null,
      importPath: null,
      sourcePath,
      category,
      label: humanize(file),
    });
  }
}

const imports = assets
  .filter((asset) => asset.identifier)
  .map((asset) => `import ${asset.identifier} from "${asset.importPath}";`)
  .join("\n");

const rows = assets
  .map((asset) => {
    const src = asset.identifier ? asset.identifier : JSON.stringify(asset.sourcePath);
    return `  {
    key: ${JSON.stringify(basename(asset.sourcePath))},
    label: ${JSON.stringify(asset.label)},
    category: ${JSON.stringify(asset.category)},
    sourcePath: ${JSON.stringify(asset.sourcePath)},
    src: ${src},
  },`;
  })
  .join("\n");

const output = `// This file is generated by scripts/generate-image-assets.mjs.
// Run \`pnpm generate:images\` (also runs before dev/build) instead of editing it by hand.

${imports ? `${imports}\n` : ""}
export type ImageAssetCategory =
  | "characters"
  | "npc"
  | "enemies"
  | "items"
  | "spells"
  | "backgrounds"
  | "other";

export interface ImageAsset {
  /** File name, including the extension. */
  key: string;
  /** Human-readable name for the admin picker. */
  label: string;
  category: ImageAssetCategory;
  /** Stable value to store in the database. */
  sourcePath: string;
  /** URL used by the app. */
  src: string;
}

export const IMAGE_ASSET_CATEGORIES: { id: ImageAssetCategory; label: string }[] = [
  { id: "characters", label: "Characters" },
  { id: "npc", label: "NPCs" },
  { id: "enemies", label: "Enemies" },
  { id: "items", label: "Items" },
  { id: "spells", label: "Spells" },
  { id: "backgrounds", label: "Backgrounds" },
  { id: "other", label: "Other" },
];

export const IMAGE_ASSETS: ImageAsset[] = [
${rows}
];
`;

const outFile = join(root, "src/data/imageAssets.ts");
mkdirSync(join(root, "src/data"), { recursive: true });
writeFileSync(outFile, output);
console.log(`Generated ${outFile} with ${assets.length} image assets.`);
